#include "config.h"

#include "nerv_status.h"
#include "nerv_types.h"

/* 平台编号与平台选择. */

_Static_assert(NERV_PLATFORM_NONE == 0U, "NERV_PLATFORM_NONE must be 0.");
_Static_assert(NERV_PLATFORM_STM32H7 == 1U, "NERV_PLATFORM_STM32H7 must be 1.");
_Static_assert(NERV_PLATFORM_CUSTOM == 2U, "NERV_PLATFORM_CUSTOM must be 2.");

_Static_assert((NERV_PLATFORM == NERV_PLATFORM_STM32H7) || (NERV_PLATFORM == NERV_PLATFORM_CUSTOM),
               "NERV_PLATFORM must select a supported platform.");

/* 模块裁剪开关. */

_Static_assert((NERV_USE_LOG == 0) || (NERV_USE_LOG == 1), "NERV_USE_LOG must be 0 or 1.");
_Static_assert((NERV_USE_CHASSIS == 0) || (NERV_USE_CHASSIS == 1),
               "NERV_USE_CHASSIS must be 0 or 1.");
_Static_assert((NERV_USE_GIMBAL == 0) || (NERV_USE_GIMBAL == 1), "NERV_USE_GIMBAL must be 0 or 1.");
_Static_assert((NERV_USE_SHOOT == 0) || (NERV_USE_SHOOT == 1), "NERV_USE_SHOOT must be 0 or 1.");
_Static_assert((NERV_USE_SAFETY == 0) || (NERV_USE_SAFETY == 1), "NERV_USE_SAFETY must be 0 or 1.");

/* 底盘配置. 模块关闭时不检查其专属宏. */

#if (NERV_USE_CHASSIS != 0)

_Static_assert(NERV_CHASSIS_TYPE_MECANUM == 1U, "NERV_CHASSIS_TYPE_MECANUM must be 1.");
_Static_assert(NERV_CHASSIS_TYPE_OMNI == 2U, "NERV_CHASSIS_TYPE_OMNI must be 2.");
_Static_assert(NERV_CHASSIS_TYPE_STEERING == 3U, "NERV_CHASSIS_TYPE_STEERING must be 3.");

_Static_assert((NERV_CHASSIS_TYPE == NERV_CHASSIS_TYPE_MECANUM) ||
                   (NERV_CHASSIS_TYPE == NERV_CHASSIS_TYPE_OMNI) ||
                   (NERV_CHASSIS_TYPE == NERV_CHASSIS_TYPE_STEERING),
               "NERV_CHASSIS_TYPE must select a supported chassis.");

#endif /* NERV_USE_CHASSIS */

/* 电机协议族. 电机模块没有独立裁剪开关. */

_Static_assert(NERV_MOTOR_PROTOCOL_RM_CAN == 1U, "NERV_MOTOR_PROTOCOL_RM_CAN must be 1.");
_Static_assert(NERV_MOTOR_PROTOCOL_CUSTOM == 2U, "NERV_MOTOR_PROTOCOL_CUSTOM must be 2.");

_Static_assert((NERV_MOTOR_PROTOCOL == NERV_MOTOR_PROTOCOL_RM_CAN) ||
                   (NERV_MOTOR_PROTOCOL == NERV_MOTOR_PROTOCOL_CUSTOM),
               "NERV_MOTOR_PROTOCOL must select a supported protocol.");

/* 云台配置. 模块关闭时不检查其专属宏. */

#if (NERV_USE_GIMBAL != 0)

_Static_assert(NERV_GIMBAL_AXIS_COUNT_2 == 2U, "NERV_GIMBAL_AXIS_COUNT_2 must be 2.");
_Static_assert(NERV_GIMBAL_AXIS_COUNT_3 == 3U, "NERV_GIMBAL_AXIS_COUNT_3 must be 3.");

_Static_assert((NERV_GIMBAL_AXIS_COUNT == NERV_GIMBAL_AXIS_COUNT_2) ||
                   (NERV_GIMBAL_AXIS_COUNT == NERV_GIMBAL_AXIS_COUNT_3),
               "NERV_GIMBAL_AXIS_COUNT must be 2 or 3.");

#endif /* NERV_USE_GIMBAL */

/* 板间通信链路. */

_Static_assert(NERV_BOARD_LINK_FDCAN == 1U, "NERV_BOARD_LINK_FDCAN must be 1.");
_Static_assert(NERV_BOARD_LINK_UART == 2U, "NERV_BOARD_LINK_UART must be 2.");

_Static_assert((NERV_BOARD_LINK == NERV_BOARD_LINK_FDCAN) ||
                   (NERV_BOARD_LINK == NERV_BOARD_LINK_UART),
               "NERV_BOARD_LINK must select a supported link.");

/* 日志配置. 模块关闭时不检查其专属宏. */

#if (NERV_USE_LOG != 0)

_Static_assert(NERV_LOG_LEVEL_ERROR == 0U, "NERV_LOG_LEVEL_ERROR must be 0.");
_Static_assert(NERV_LOG_LEVEL_WARN == 1U, "NERV_LOG_LEVEL_WARN must be 1.");
_Static_assert(NERV_LOG_LEVEL_INFO == 2U, "NERV_LOG_LEVEL_INFO must be 2.");
_Static_assert(NERV_LOG_LEVEL_DEBUG == 3U, "NERV_LOG_LEVEL_DEBUG must be 3.");

_Static_assert((NERV_LOG_LEVEL >= NERV_LOG_LEVEL_ERROR) && (NERV_LOG_LEVEL <= NERV_LOG_LEVEL_DEBUG),
               "NERV_LOG_LEVEL is invalid.");
_Static_assert((NERV_LOG_MSG_MAX >= 32U) && (NERV_LOG_MSG_MAX <= 512U),
               "NERV_LOG_MSG_MAX must be in range 32 to 512.");
_Static_assert((NERV_LOG_USE_FLOAT == 0) || (NERV_LOG_USE_FLOAT == 1),
               "NERV_LOG_USE_FLOAT must be 0 or 1.");

#endif /* NERV_USE_LOG */

/* 基础状态码. */

_Static_assert((int)NERV_OK == 0, "NERV_OK must be 0.");
_Static_assert((int)NERV_ERROR == 1, "NERV_ERROR must be 1.");
_Static_assert((int)NERV_BUSY == 2, "NERV_BUSY must be 2.");
_Static_assert((int)NERV_TIMEOUT == 3, "NERV_TIMEOUT must be 3.");

/* 错误码域号. */

_Static_assert(NERV_ERR_NONE == 0U, "NERV_ERR_NONE must be 0.");
_Static_assert(NERV_ERR_ALL == 0xFFFFFFFFU, "NERV_ERR_ALL must be all ones.");
_Static_assert(NERV_ERR_BITS_MASK == 0x00FFFFFFU, "NERV_ERR_BITS_MASK must cover the low 24 bits.");

_Static_assert(NERV_ERR_DOMAIN_COMMON == 0x01U, "NERV_ERR_DOMAIN_COMMON must be one-hot.");
_Static_assert(NERV_ERR_DOMAIN_FDCAN == 0x02U, "NERV_ERR_DOMAIN_FDCAN must be one-hot.");
_Static_assert(NERV_ERR_DOMAIN_MOTOR == 0x04U, "NERV_ERR_DOMAIN_MOTOR must be one-hot.");
_Static_assert(NERV_ERR_DOMAIN_CHASSIS == 0x08U, "NERV_ERR_DOMAIN_CHASSIS must be one-hot.");
_Static_assert(NERV_ERR_DOMAIN_GIMBAL == 0x10U, "NERV_ERR_DOMAIN_GIMBAL must be one-hot.");
_Static_assert(NERV_ERR_DOMAIN_SHOOT == 0x20U, "NERV_ERR_DOMAIN_SHOOT must be one-hot.");
_Static_assert(NERV_ERR_DOMAIN_SAFETY == 0x40U, "NERV_ERR_DOMAIN_SAFETY must be one-hot.");

_Static_assert(NERV_ERR_DOMAIN(NERV_ERR_DOMAIN_COMMON) == 0x01000000U,
               "NERV_ERR_DOMAIN must place the domain in the high byte.");
_Static_assert(NERV_ERR_DOMAIN(NERV_ERR_DOMAIN_SAFETY) == 0x40000000U,
               "NERV_ERR_DOMAIN must place the domain in the high byte.");
_Static_assert(NERV_ERR_BIT(0U) == 0x00000001U, "NERV_ERR_BIT(0) must set bit 0.");
_Static_assert(NERV_ERR_BIT(23U) == 0x00800000U, "NERV_ERR_BIT(23) must set bit 23.");

/* 低 24 位按域分段. */

_Static_assert(NERV_ERR_COMMON_BITS_MASK == 0x0000003FU,
               "NERV_ERR_COMMON_BITS_MASK must cover bits 0 to 5.");
_Static_assert(NERV_ERR_FDCAN_BITS_MASK == 0x000001C0U,
               "NERV_ERR_FDCAN_BITS_MASK must cover bits 6 to 8.");
_Static_assert(NERV_ERR_MOTOR_BITS_MASK == 0x00000600U,
               "NERV_ERR_MOTOR_BITS_MASK must cover bits 9 to 10.");
_Static_assert(NERV_ERR_CHASSIS_BITS_MASK == 0x00001800U,
               "NERV_ERR_CHASSIS_BITS_MASK must cover bits 11 to 12.");
_Static_assert(NERV_ERR_GIMBAL_BITS_MASK == 0x00006000U,
               "NERV_ERR_GIMBAL_BITS_MASK must cover bits 13 to 14.");
_Static_assert(NERV_ERR_SHOOT_BITS_MASK == 0x00018000U,
               "NERV_ERR_SHOOT_BITS_MASK must cover bits 15 to 16.");
_Static_assert(NERV_ERR_SAFETY_BITS_MASK == 0x00060000U,
               "NERV_ERR_SAFETY_BITS_MASK must cover bits 17 to 18.");

/** @cond INTERNAL */

#define __NERV_CONFIG_CHECK_ERROR_BITS_MASK                                              \
    (NERV_ERR_COMMON_BITS_MASK | NERV_ERR_FDCAN_BITS_MASK | NERV_ERR_MOTOR_BITS_MASK |   \
     NERV_ERR_CHASSIS_BITS_MASK | NERV_ERR_GIMBAL_BITS_MASK | NERV_ERR_SHOOT_BITS_MASK | \
     NERV_ERR_SAFETY_BITS_MASK)

_Static_assert(__NERV_CONFIG_CHECK_ERROR_BITS_MASK == 0x0007FFFFU,
               "Domain error bits must cover bits 0 to 18 and leave bits 19 to 23 spare.");

/* 错误码的域号, 位号与位范围必须与定义一致. 位号是低 24 位中的全局位号. */

#define __NERV_CONFIG_CHECK_ERROR(_code, _domain, _bit, _mask)                   \
    _Static_assert((((_code) >> 24U) == (_domain)) &&                            \
                       (((_code) & NERV_ERR_BITS_MASK) == NERV_ERR_BIT(_bit)) && \
                       (((_code) & NERV_ERR_BITS_MASK & ~(_mask)) == 0U),        \
                   #_code " must use its assigned domain, bit and bit range.")

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_COMMON_INVALID_PARAM, NERV_ERR_DOMAIN_COMMON, 0U,
                          NERV_ERR_COMMON_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_COMMON_NULL_PTR, NERV_ERR_DOMAIN_COMMON, 1U,
                          NERV_ERR_COMMON_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_COMMON_NOT_INITIALIZED, NERV_ERR_DOMAIN_COMMON, 2U,
                          NERV_ERR_COMMON_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_COMMON_NO_MEMORY, NERV_ERR_DOMAIN_COMMON, 3U,
                          NERV_ERR_COMMON_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_COMMON_OUT_OF_RANGE, NERV_ERR_DOMAIN_COMMON, 4U,
                          NERV_ERR_COMMON_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_COMMON_NOT_SUPPORTED, NERV_ERR_DOMAIN_COMMON, 5U,
                          NERV_ERR_COMMON_BITS_MASK);

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_FDCAN_FILTER, NERV_ERR_DOMAIN_FDCAN, 6U,
                          NERV_ERR_FDCAN_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_FDCAN_TX_MAILBOX, NERV_ERR_DOMAIN_FDCAN, 7U,
                          NERV_ERR_FDCAN_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_FDCAN_RX_OVERRUN, NERV_ERR_DOMAIN_FDCAN, 8U,
                          NERV_ERR_FDCAN_BITS_MASK);

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_MOTOR_OFFLINE, NERV_ERR_DOMAIN_MOTOR, 9U,
                          NERV_ERR_MOTOR_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_MOTOR_OVER_TEMP, NERV_ERR_DOMAIN_MOTOR, 10U,
                          NERV_ERR_MOTOR_BITS_MASK);

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_CHASSIS_KINEMATICS, NERV_ERR_DOMAIN_CHASSIS, 11U,
                          NERV_ERR_CHASSIS_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_CHASSIS_WHEEL_OFFLINE, NERV_ERR_DOMAIN_CHASSIS, 12U,
                          NERV_ERR_CHASSIS_BITS_MASK);

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_GIMBAL_LIMIT, NERV_ERR_DOMAIN_GIMBAL, 13U,
                          NERV_ERR_GIMBAL_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_GIMBAL_OFFLINE, NERV_ERR_DOMAIN_GIMBAL, 14U,
                          NERV_ERR_GIMBAL_BITS_MASK);

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_SHOOT_JAM, NERV_ERR_DOMAIN_SHOOT, 15U, NERV_ERR_SHOOT_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_SHOOT_OFFLINE, NERV_ERR_DOMAIN_SHOOT, 16U,
                          NERV_ERR_SHOOT_BITS_MASK);

__NERV_CONFIG_CHECK_ERROR(NERV_ERR_SAFETY_ESTOP, NERV_ERR_DOMAIN_SAFETY, 17U,
                          NERV_ERR_SAFETY_BITS_MASK);
__NERV_CONFIG_CHECK_ERROR(NERV_ERR_SAFETY_LATCHED, NERV_ERR_DOMAIN_SAFETY, 18U,
                          NERV_ERR_SAFETY_BITS_MASK);

/* 同一域内的错误码不得重复. */

#define __NERV_CONFIG_CHECK_ERROR_DISTINCT(_a, _b) \
    _Static_assert((_a) != (_b), #_a " and " #_b " must be distinct.")

__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_INVALID_PARAM, NERV_ERR_COMMON_NULL_PTR);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_INVALID_PARAM, NERV_ERR_COMMON_NOT_INITIALIZED);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_INVALID_PARAM, NERV_ERR_COMMON_NO_MEMORY);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_INVALID_PARAM, NERV_ERR_COMMON_OUT_OF_RANGE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_INVALID_PARAM, NERV_ERR_COMMON_NOT_SUPPORTED);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NULL_PTR, NERV_ERR_COMMON_NOT_INITIALIZED);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NULL_PTR, NERV_ERR_COMMON_NO_MEMORY);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NULL_PTR, NERV_ERR_COMMON_OUT_OF_RANGE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NULL_PTR, NERV_ERR_COMMON_NOT_SUPPORTED);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NOT_INITIALIZED, NERV_ERR_COMMON_NO_MEMORY);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NOT_INITIALIZED, NERV_ERR_COMMON_OUT_OF_RANGE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NOT_INITIALIZED, NERV_ERR_COMMON_NOT_SUPPORTED);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NO_MEMORY, NERV_ERR_COMMON_OUT_OF_RANGE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_NO_MEMORY, NERV_ERR_COMMON_NOT_SUPPORTED);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_COMMON_OUT_OF_RANGE, NERV_ERR_COMMON_NOT_SUPPORTED);

__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_FDCAN_FILTER, NERV_ERR_FDCAN_TX_MAILBOX);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_FDCAN_FILTER, NERV_ERR_FDCAN_RX_OVERRUN);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_FDCAN_TX_MAILBOX, NERV_ERR_FDCAN_RX_OVERRUN);

__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_MOTOR_OFFLINE, NERV_ERR_MOTOR_OVER_TEMP);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_CHASSIS_KINEMATICS, NERV_ERR_CHASSIS_WHEEL_OFFLINE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_GIMBAL_LIMIT, NERV_ERR_GIMBAL_OFFLINE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_SHOOT_JAM, NERV_ERR_SHOOT_OFFLINE);
__NERV_CONFIG_CHECK_ERROR_DISTINCT(NERV_ERR_SAFETY_ESTOP, NERV_ERR_SAFETY_LATCHED);

